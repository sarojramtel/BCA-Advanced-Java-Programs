package swing.mvc2;

public class StudentModel {

    String hobby;
    boolean programming;

    public void setHobby(String hobby) {
        this.hobby = hobby;
    }

    public void setProgramming(boolean programming) {
        this.programming = programming;
    }

    public String getHobby() {
        return hobby;
    }

    public boolean getProgramming() {
        return programming;
    }
}